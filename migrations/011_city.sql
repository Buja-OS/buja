-- News: cached articles from Nigerian outlets, filtered to Abuja and the FCT.
CREATE TABLE IF NOT EXISTS news_items (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  title       VARCHAR(250) NOT NULL,
  summary     VARCHAR(600) NULL,
  url         VARCHAR(500) NOT NULL,
  source      VARCHAR(60) NOT NULL,
  category    VARCHAR(20) NOT NULL DEFAULT 'general',
  priority    TINYINT UNSIGNED NOT NULL DEFAULT 0,
  published_at DATETIME NOT NULL,
  url_hash    CHAR(40) NOT NULL,
  pushed_at   DATETIME NULL,
  created_at  DATETIME NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_news_url (url_hash),
  KEY ix_news_feed (published_at),
  KEY ix_news_priority (priority, published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Abuja Social: a forum. Posts belong to a board, carry optional district, and can be answered and liked.
CREATE TABLE IF NOT EXISTS social_posts (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id    BIGINT UNSIGNED NOT NULL,
  board      VARCHAR(20) NOT NULL,
  title      VARCHAR(140) NOT NULL,
  body       VARCHAR(4000) NOT NULL,
  district   VARCHAR(60) NULL,
  replies    INT UNSIGNED NOT NULL DEFAULT 0,
  likes      INT UNSIGNED NOT NULL DEFAULT 0,
  views      INT UNSIGNED NOT NULL DEFAULT 0,
  pinned     TINYINT(1) NOT NULL DEFAULT 0,
  hidden_at  DATETIME NULL,
  last_activity_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  KEY ix_social_feed (hidden_at, board, last_activity_at),
  CONSTRAINT fk_social_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS social_replies (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  post_id    BIGINT UNSIGNED NOT NULL,
  user_id    BIGINT UNSIGNED NOT NULL,
  body       VARCHAR(2000) NOT NULL,
  likes      INT UNSIGNED NOT NULL DEFAULT 0,
  hidden_at  DATETIME NULL,
  created_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  KEY ix_reply_post (post_id, id),
  CONSTRAINT fk_reply_post FOREIGN KEY (post_id) REFERENCES social_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS social_likes (
  user_id    BIGINT UNSIGNED NOT NULL,
  kind       ENUM('post','reply') NOT NULL,
  target_id  BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL,
  PRIMARY KEY (user_id, kind, target_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Match: remember who we have already suggested, so nobody is pinged twice about the same person.
CREATE TABLE IF NOT EXISTS match_suggestions (
  user_id     BIGINT UNSIGNED NOT NULL,
  suggested   BIGINT UNSIGNED NOT NULL,
  created_at  DATETIME NOT NULL,
  PRIMARY KEY (user_id, suggested)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

